function renderMarkdown(text) {
  return text
    .trim()
    .split('\n')
    .map((line, i) => {
      if (line.startsWith('## ')) return <h2 key={i} className="text-xl font-extrabold text-slate-800 mt-8 mb-3">{line.slice(3)}</h2>;
      if (line.startsWith('### ')) return <h3 key={i} className="text-base font-bold text-slate-700 mt-5 mb-2">{line.slice(4)}</h3>;
      if (line.startsWith('- ')) return <li key={i} className="text-slate-600 text-sm leading-relaxed mr-4 list-disc">{line.slice(2)}</li>;
      if (line.match(/^\d+\. /)) return <li key={i} className="text-slate-600 text-sm leading-relaxed mr-4 list-decimal">{line.replace(/^\d+\. /, '')}</li>;
      if (line.startsWith('**') && line.endsWith('**')) return <p key={i} className="font-bold text-slate-700 mt-3 mb-1">{line.slice(2, -2)}</p>;
      if (line.includes('[') && line.includes('](/')) {
        const match = line.match(/\[(.+?)\]\((.+?)\)/);
        if (match) return <p key={i} className="mt-4"><Link to={match[2]} className="inline-block bg-violet-600 text-white px-6 py-2.5 rounded-full font-bold text-sm hover:bg-violet-700 transition">{match[1]}</Link></p>;
      }
      if (line === '') return <div key={i} className="h-2" />;
      return <p key={i} className="text-slate-600 text-sm leading-relaxed">{line}</p>;
    });
}

